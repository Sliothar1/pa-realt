"""Build site/list.html: the non-map equivalent of the monument map (static table, no JS needed).
Reads site/data/sites.json + site/data/standing.json. Run after scripts/d4m_build.py:
    python3 scripts/build_list.py"""
import html, json, os
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
S = json.load(open('site/data/sites.json', encoding='utf-8')); M = S['meta']
rows = S['sites'] + json.load(open('site/data/standing.json', encoding='utf-8'))['sites']
G = M['groups']; order = list(G)
rows.sort(key=lambda s: (order.index(s[1]) if s[1] in order else 99, M['counties'][s[6]], s[4], s[0]))
e = html.escape


def ga(t):
    t = (t or '').strip()
    return '<span lang="ga">%s</span>' % e(t) if t else ''


out, cur = [], None
for s in rows:
    if s[1] != cur:
        if cur is not None:
            out.append('</tbody></table></div>')
        cur = s[1]; g = G.get(cur, {'en': cur, 'ga': None})
        n = sum(1 for r in rows if r[1] == cur)
        out.append('<h2 id="g-%s">%s %s <span class="soft">(%s)</span></h2>' % (cur, e(g['en']), ('· ' + ga(g['ga'])) if g.get('ga') else '', format(n, ',')))
        out.append('<div class="credits-wrap"><table class="credits"><thead><tr><th scope="col">SMR</th><th scope="col">Townland</th>'
                   '<th scope="col"><span lang="ga">Baile fearainn</span></th><th scope="col">County</th><th scope="col">Visit sheet</th></tr></thead><tbody>')
    c = s[6]
    cty = e(M['counties'][c].title()) + ((' · ' + ga(M['counties_ga'][c])) if M.get('counties_ga') and M['counties_ga'][c] else '')
    out.append('<tr><td><a href="./#site=%s">%s</a></td><td>%s</td><td>%s</td><td>%s</td><td><a href="visit.html?site=%s">sheet</a></td></tr>'
               % (e(s[0]), e(s[0].rstrip('-')), e(s[4]), ga(s[5]), cty, e(s[0])))
out.append('</tbody></table></div>')
toc = ' · '.join('<a href="#g-%s">%s</a>' % (k, e(v['en'])) for k, v in G.items() if any(r[1] == k for r in rows))
page = '''<!doctype html>
<html lang="en" data-theme="night"><head><meta charset="utf-8"><!--SEC:csp-2026-10-12--><meta http-equiv="Content-Security-Policy" content="default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob: https://tile.openstreetmap.org; font-src 'self'; connect-src 'self'; worker-src 'none'; object-src 'none'; base-uri 'self'; form-action 'self'; frame-src 'none'"><meta name="referrer" content="strict-origin-when-cross-origin"><meta http-equiv="X-Content-Type-Options" content="nosniff"><meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Monument list · Liosta séadchomharthaí · PA Réalt</title>
<meta name="description" content="All %s monuments on the PA Réalt map as a plain list, by type and county: the non-map equivalent of the map.">
<meta name="theme-color" content="#1a080c"><link rel="canonical" href="https://sliothar1.github.io/pa-realt/list.html"><link rel="icon" href="assets/icon.svg" type="image/svg+xml"><link rel="stylesheet" href="styles.css"><link rel="stylesheet" href="pages.css">
<script>(function(){try{var t=localStorage.getItem('pa-realt-theme');if(t)document.documentElement.setAttribute('data-theme',t)}catch(e){}})();</script>
</head><body class="subpage">
<a class="skip" href="#main">Skip to content · <span lang="ga">Léim go dtí an t-ábhar</span></a>
<header class="minihead"><div class="wrap"><a class="brandlink" href="./"><img src="assets/icon.svg" alt="" width="28" height="28"><span class="brand">PA Réalt</span></a><a class="toplink" href="./">← Back to the map</a></div></header>
<main class="wrap page" id="main">
<p class="eyebrow"><i lang="ga">Liosta séadchomharthaí</i> · Monument list</p>
<h1>Every monument on the map, as a list</h1>
<p class="lead">The same %s monuments as the map, grouped by type, then county and townland. Use your browser's find (Ctrl+F) to search. Each SMR number opens the monument on the map; "sheet" opens its printable visit sheet.</p>
<p class="note">Jump to: %s</p>
%s
<p class="note">Data: %s. Generated by scripts/build_list.py.</p>
</main>
<footer>
<p class="pa-credit">Designed and built by Garry Lohan · <a href="https://scholar.google.com/citations?user=9aBECzQAAAAJ&amp;hl=en" target="_blank" rel="noopener">Google Scholar</a> · <a href="https://www.linkedin.com/in/garry-lohan-14923814" target="_blank" rel="noopener">LinkedIn</a></p>
</footer>
</body></html>
''' % (format(len(rows), ','), format(len(rows), ','), toc, '\n'.join(out), e(M['source']))
open('site/list.html', 'w', encoding='utf-8').write(page)
print('ok', len(rows), 'rows', len(page), 'bytes')
